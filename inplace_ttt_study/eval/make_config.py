"""Write an OpenCompass config that runs RULER (13 tasks) for several model variants at one context length.

Mirrors upstream In-Place-TTT/eval_config/ruler_*.py (the setup used by the paper): the full RULER task
set, 64 generated tokens, greedy decoding, base-model prompting. Differences: the model type is
TTTHuggingFaceModel (registers the TTT classes in each worker) and the variants are given on the
command line (see variants.py for the spec syntax).

    python -m inplace_ttt_study.eval.make_config --length 32k --num-samples 100 --workers 4 \
        --variants-dir runs/variants --out runs/results/ruler_32k/config.py base=runs/models/Qwen3-4B-Base
"""
import argparse
import os

from .variants import make_variant, parse_spec

TEMPLATE = '''# Generated by inplace_ttt_study.eval.make_config; mirrors upstream eval_config/ruler_*.py.
from mmengine.config import read_base
from opencompass.partitioners import NaivePartitioner, NumWorkerPartitioner
from opencompass.runners import LocalRunner
from opencompass.tasks import OpenICLEvalTask, OpenICLInferTask
from inplace_ttt_study.eval.ttt_model import TTTHuggingFaceModel

with read_base():
    from opencompass.configs.datasets.ruler.ruler_cwe_gen import cwe_datasets
    from opencompass.configs.datasets.ruler.ruler_fwe_gen import fwe_datasets
    from opencompass.configs.datasets.ruler.ruler_niah_gen import niah_datasets
    from opencompass.configs.datasets.ruler.ruler_qa_gen import qa_datasets
    from opencompass.configs.datasets.ruler.ruler_vt_gen import vt_datasets
    from opencompass.configs.summarizers.groups.ruler import ruler_summary_groups

MAX_SEQ_LEN, SUFFIX, NUM_SAMPLES = {max_seq_len}, "{suffix}", {num_samples}
VARIANTS = {variants}  # name -> model directory

models, datasets, model_dataset_combinations = [], [], []
for name, path in VARIANTS.items():
    model = dict(type=TTTHuggingFaceModel, abbr=name, path=path, max_seq_len=131072, max_out_len=64,
                 batch_size=1, run_cfg=dict(num_gpus=1), generation_kwargs=dict(do_sample=False))
    tasks = []
    for d in sum([qa_datasets, niah_datasets, vt_datasets, fwe_datasets, cwe_datasets], []):
        d = d.deepcopy()
        d["abbr"] += "_" + SUFFIX
        d.update(tokenizer_model=path, num_samples=NUM_SAMPLES, max_seq_length=MAX_SEQ_LEN)
        tasks.append(d)
    models.append(model)
    datasets.extend(tasks)
    model_dataset_combinations.append(dict(models=[model], datasets=tasks))

infer = dict(partitioner=dict(type=NumWorkerPartitioner, num_worker={workers}),
             runner=dict(type=LocalRunner, max_num_workers={workers}, task=dict(type=OpenICLInferTask), retry=2))
eval = dict(partitioner=dict(type=NaivePartitioner),
            runner=dict(type=LocalRunner, max_num_workers=16, task=dict(type=OpenICLEvalTask)))
summarizer = dict(dataset_abbrs=["ruler_" + SUFFIX] + [d["abbr"] for d in datasets], summary_groups=ruler_summary_groups)
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--length", required=True, help="context length such as 4k, 32k, 64k, 128k")
    ap.add_argument("--num-samples", type=int, default=500)
    ap.add_argument("--workers", type=int, default=4, help="GPUs available to the run")
    ap.add_argument("--variants-dir", required=True)
    ap.add_argument("--out", required=True, help="path of the generated config file")
    ap.add_argument("specs", nargs="+", help="name=path[:key=value,...]")
    args = ap.parse_args()
    variants = {}
    for spec in args.specs:
        name, path, overrides = parse_spec(spec)
        variants[name] = make_variant(name, path, overrides, args.variants_dir)
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        f.write(TEMPLATE.format(max_seq_len=int(args.length.rstrip("k")) * 1024, suffix=args.length,
                                num_samples=args.num_samples, variants=variants, workers=args.workers))
    print(args.out)


if __name__ == "__main__":
    main()
